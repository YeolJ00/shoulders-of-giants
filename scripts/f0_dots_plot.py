"""Draw the dot trajectories: what the SIMULATOR proposes vs what the motion prior expects.

Neither is ground truth. The simulator's path is a CANDIDATE produced by the theta we are
trying to fit; the prior's modes are a criterion candidate. Putting them on the same frame
is the point -- plausibility is judged by eye here, not asserted.
"""
import base64, io, json
from pathlib import Path

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import imageio.v2 as imageio

D = json.load(open("docs/results/f0_dots.json"))
cards = []
for o in D:
    rd = imageio.get_reader(f"{o['lab']}/clips/{o['key']}.mp4")
    frames = [f[..., :3] for f in rd]; rd.close()
    side = o["side"]
    sim = np.array(o["sim"]) * side              # (T, n, 2) in clip pixels
    w = np.array(o["weights"])[0]
    mu = np.array(o["means"])[0] * side          # (K, 2)
    fig, ax = plt.subplots(figsize=(5.2, 5.2), dpi=150)
    ax.imshow(frames[0], extent=[0, side, side, 0])
    # the simulator's proposed path, one line per tracked point
    for j in range(sim.shape[1]):
        ax.plot(sim[:, j, 0], sim[:, j, 1], "-", color="#2b5f86", lw=1.4, alpha=0.9,
                zorder=3)
        ax.scatter(sim[::6, j, 0], sim[::6, j, 1], s=7, color="#2b5f86", zorder=4)
    ax.scatter(sim[0, :, 0], sim[0, :, 1], s=34, facecolor="none",
               edgecolor="#f0f0f0", lw=1.6, zorder=5)
    # the prior's modes, as arrows from each start point, opacity by weight
    for k in range(len(w)):
        for j in range(sim.shape[1]):
            ax.arrow(sim[0, j, 0], sim[0, j, 1], mu[k, 0], mu[k, 1],
                     color="#c8501d", width=1.1, head_width=6,
                     alpha=float(np.clip(w[k], 0.06, 1.0)), length_includes_head=True,
                     zorder=6)
    ax.set_xlim(0, side); ax.set_ylim(side, 0); ax.axis("off")
    fig.tight_layout(pad=0.1)
    b = io.BytesIO(); fig.savefig(b, format="png", dpi=150); plt.close(fig)
    u = "data:image/png;base64," + base64.b64encode(b.getvalue()).decode()
    d0 = np.linalg.norm(sim[24] - sim[0], axis=-1).mean()
    modes = " &middot; ".join(f"{np.linalg.norm(mu[k]):.0f} px at weight {w[k]:.2f}"
                             for k in np.argsort(-w))
    cards.append((o["label"], u, d0, modes))

STYLE = Path("docs/V_TRACK.html").read_text().split("<style>")[1].split("</style>")[0]
body = "".join(f"""
<h2>{lab}</h2>
<div class="pair"><img src="{u}" alt="">
<div class="leg"><p><b class="sim">Blue</b> &mdash; the path the <em>simulator proposes</em>
over one second, six tracked points, dots every six frames. Mean displacement
<b>{d:.0f} px</b>.</p>
<p><b class="pri">Orange</b> &mdash; the motion prior's four modes as arrows from each
start point, opacity by weight: {m}.</p></div></div>""" for lab, u, d, m in cards)

H = f"""<title>Dot Trajectories</title>
<style>{STYLE}
.pair{{display:grid;grid-template-columns:minmax(260px,1fr) minmax(220px,1fr);gap:18px;
 align-items:start;margin:16px 0 30px}}
.pair img{{width:100%;border:1px solid var(--rule);border-radius:3px;display:block}}
.leg p{{font-size:14px;margin:0 0 12px}}
b.sim{{color:#2b5f86}} b.pri{{color:#c8501d}}
</style>
<div class="wrap">
<header>
<div class="eyebrow">reify &middot; dot trajectories</div>
<h1>What the simulator proposes, against what a motion prior expects</h1>
<p class="lede">Neither line is ground truth. The blue path is a <em>candidate</em> produced
by the &theta; we are trying to fit; the orange arrows are a criterion candidate. The point
of drawing them together is that plausibility gets judged by eye rather than asserted.</p>
</header>
{body}
<div class="note"><b>The prior returns almost the same four modes whatever it is shown.</b>
A bowl in mid-air gives 0.7 / 7.4 / 44.3 / 27.2 px; a sorter resting on a ramp gives
0.6 / 4.5 / 39.9 / 20.4. In every case ~0.99 of the weight sits on the near-zero mode. So
the arrows barely change between a scene where something must fall and one where it may
not move at all.</div>
<footer>reify &middot; generated by scripts/f0_dots_plot.py &middot; geometry from
docs/results/f0_dots.json</footer></div>"""
Path("docs/DOTS.html").write_text(H)
print(f"wrote docs/DOTS.html ({len(H)/1e6:.2f} MB, {len(cards)} scenes)")
